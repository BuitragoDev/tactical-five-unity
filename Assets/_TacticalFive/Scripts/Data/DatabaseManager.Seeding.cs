    /// <summary>
    /// Siembra el historial de carrera y los anillos iniciales de los jugadores activos
    /// (roster + agentes libres) para que, al retirarse, puedan entrar de forma justa
    /// al Salón de la Fama según su carrera previa a la partida.
    /// Idempotente: no toca a jugadores que ya tengan fila en historical_player_stats.
    /// </summary>
    public void SeedActivePlayerCareers()
    {
        var allPlayers = _db.Table<PlayerData>().ToList();
        if (allPlayers.Count == 0) return;

        // El seeder histórico ya contiene la carrera real de los jugadores que siguen
        // activos. Esa fila es la fuente correcta; la carrera sintética solo se usa para
        // jugadores que no aparecen en el histórico.
        var countsByName = allPlayers
            .GroupBy(p => SeededCareerRules.NameKey(p.first_name, p.last_name))
            .ToDictionary(g => g.Key, g => g.Count());

        var unowned = _db.Table<HistoricalPlayerStatsData>()
            .Where(h => h.player_id <= 0)
            .ToList();
        var gameTotals = BuildCareerGameTotals(includeCurrentSeason: false);

        int adopted = 0;
        int seeded = 0;
        foreach (var p in allPlayers)
        {
            if (GetHistoricalPlayerStats(p.id) != null) continue;

            string key = SeededCareerRules.NameKey(p.first_name, p.last_name);
            HistoricalPlayerStatsData seedRow =
                countsByName.TryGetValue(key, out int sameName) && sameName == 1
                    ? SeededCareerRules.FindUniqueSeedRow(unowned, p.first_name, p.last_name)
                    : null;

            if (seedRow != null)
            {
                if (seedRow.games > 0)
                {
                    gameTotals.TryGetValue(p.id, out var played);
                    var merged = SeededCareerRules.Merge(seedRow, played);
                    merged.id = 0;
                    merged.player_id = p.id;
                    merged.first_name = p.first_name;
                    merged.last_name = p.last_name;
                    merged.position = string.IsNullOrEmpty(p.position) ? seedRow.position : p.position;
                    merged.overall = p.overall;

                    var team = GetTeamById(p.team_id);
                    if (team != null)
                    {
                        merged.team_name = team.name;
                        merged.team_abbreviation = team.abbreviation;
                        merged.team_logo = team.logo;
                    }

                    SaveHistoricalPlayerStats(merged);
                    _db.Delete(seedRow);
                    unowned.Remove(seedRow);
                    adopted++;
                    continue;
                }

                // Fila del seeder sin partidos (p. ej. un rookie sin carrera NBA):
                // se elimina el duplicado y el jugador empieza desde cero.
                _db.Delete(seedRow);
                unowned.Remove(seedRow);
            }

            if (p.is_rookie == 1) continue;
            ApplyInitialCareer(p);
            seeded++;
        }

        if (adopted > 0 || seeded > 0)
            Debug.Log($"[DB] Carreras iniciales: {adopted} adoptadas del histórico real, " +
                      $"{seeded} sintéticas para jugadores sin carrera sembrada.");
    }

    void ApplyInitialCareer(PlayerData p)
    {
        // Carrera sintética realista: el volumen depende de la EDAD (años jugados y
        // partidos por tramo) y el RITMO de la media de atributos (OVR), no del rol.
        // Además se capa para que un jugador de roster no supere a los históricos del seeder (P25).

        const int MAX_HIST_PTS = 15535;   // P25 de los 108 históricos del seeder (top ~100)
        const int MAX_HIST_GAMES = 1600;

        // 1) Partidos jugados acumulados por tramo de edad (no 80/año toda la carrera).
        int games = 0;
        for (int s = 18; s < p.age; s++)
        {
            if (s < 28) games += 72;
            else if (s < 33) games += 66;
            else if (s < 37) games += 55;
            else games += 40;   // veteranía: menos minutos, pero nunca cesa
        }
        if (games > MAX_HIST_GAMES) games = MAX_HIST_GAMES;

        // 2) Ritmo por juego derivado de la media de atributos (OVR 0-99).
        float r = p.overall / 100f;
        float pg = Mathf.Max(0f, (p.overall - 50) * 0.36f) + 2f;
        float rb = 0, ast = 0;
        switch (p.position)
        {
            case "PG": rb = 2f + 3f * r * 0.5f; ast = (p.overall - 50) * 0.12f + 2f; break;
            case "SG": rb = 2f + 2f * r * 0.5f; ast = (p.overall - 50) * 0.08f + 1f; break;
            case "SF": rb = 3f + 3f * r * 0.5f; ast = (p.overall - 50) * 0.08f + 1f; break;
            case "PF": rb = 4f + 5f * r * 0.5f; ast = (p.overall - 50) * 0.05f + 1f; break;
            case "C":  rb = 5f + 6f * r * 0.5f; ast = (p.overall - 50) * 0.05f + 1f; break;
            default:   rb = 3f + 3f * r * 0.5f; ast = (p.overall - 50) * 0.08f + 1f; break;
        }

        int pts = Mathf.RoundToInt(pg * games);
        int totalReb = Mathf.RoundToInt(rb * games);
        int totalAst = Mathf.RoundToInt(ast * games);

        // 3) Tope duro: un jugador no-syader no puede superar los históricos (P25).
        if (pts > MAX_HIST_PTS)
        {
            float scale = (float)MAX_HIST_PTS / pts;
            pts = MAX_HIST_PTS;
            totalReb = Mathf.RoundToInt(totalReb * scale);
            totalAst = Mathf.RoundToInt(totalAst * scale);
        }

        _db.Update(p);

        var team = GetTeamById(p.team_id);
        SaveHistoricalPlayerStats(new HistoricalPlayerStatsData
        {
            player_id = p.id,
            first_name = p.first_name,
            last_name = p.last_name,
            position = p.position,
            overall = p.overall,
            team_name = team?.name ?? "",
            team_abbreviation = team?.abbreviation ?? "",
            team_logo = team?.logo ?? "",
            games = games,
            total_points = pts,
            total_rebounds = totalReb,
            total_assists = totalAst,
            total_minutes = games * 36
        });
    }

