    static void AssignSeedJerseyNumbers(List<PlayerData> players, Dictionary<string, int> teamByAbbr)
    {
        var retiredByTeam = BuildRetiredNumbersByTeam(teamByAbbr);

        foreach (var group in players.Where(p => p.team_id > 0).GroupBy(p => p.team_id))
        {
            var used = new HashSet<int>();
            var withExact = new HashSet<PlayerData>();
            foreach (var exc in exceptions)
            {
                var p = group.FirstOrDefault(x => x.first_name == exc.Key.Item1 && x.last_name == exc.Key.Item2);
                if (p == null) continue;
                p.number = exc.Value;
                used.Add(p.number);
                withExact.Add(p);
            }

            foreach (var rn in retiredByTeam)
            {
                if (rn.TeamId == group.Key && rn.Number <= 99)
                    used.Add(rn.Number);
            }

            foreach (var p in group.Where(x => !withExact.Contains(x) && x.number == 0).OrderByDescending(x => x.overall))
            {
                for (int n = 1; n <= 99; n++)
                {
                    if (used.Contains(n)) continue;
                    p.number = n;
                    used.Add(n);
                    break;
                }
            }
        }
    }

    static List<(int TeamId, int Number)> BuildRetiredNumbersByTeam(Dictionary<string, int> teamByAbbr)
    {
        var result = new List<(int TeamId, int Number)>();
        var hof = HallOfFameSeeder.Data;
        foreach (var (firstName, lastName, number) in RetiredNumberSeeder.Data)
        {
            var legend = hof.FirstOrDefault(x => x.first_name == firstName && x.last_name == lastName);
            if (legend == null) continue;
            if (teamByAbbr.TryGetValue(legend.team_abbreviation, out var tid))
                result.Add((tid, number));
        }
        foreach (var (firstName, lastName, abbr, number) in VeteranRetiredNumberSeeder.Data)
        {
            if (teamByAbbr.TryGetValue(abbr, out var tid))
                result.Add((tid, number));
        }
        return result;
    }

    int[] GeneratePositionAttrs(int ovr, string pos, string seed)
    {
        // Base positional profiles for a reference 90-OVR player
        // Order: speed, shooting, three_point, passing, dribbling,
        //        defense, rebounding, athleticism, iq, steals, blocks
        int[] profile = pos switch
        {
            "PG" => new[] { 94, 88, 92, 97, 97, 78, 62, 82, 95, 80, 50 },
            "SG" => new[] { 92, 95, 97, 85, 88, 80, 58, 85, 88, 82, 50 },
            "SF" => new[] { 88, 88, 88, 82, 80, 90, 72, 92, 85, 86, 62 },
            "PF" => new[] { 78, 78, 72, 72, 65, 95, 95, 90, 80, 72, 60 },
            "C" => new[] { 68, 72, 55, 62, 55, 98, 99, 85, 78, 65, 70 },
            _ => new[] { 85, 85, 85, 85, 85, 85, 85, 85, 85, 85, 85 }
        };

        var rng = new System.Random(StableHash(seed));
        int[] result = new int[11];
        int sum = 0;

        for (int i = 0; i < 11; i++)
        {
            float ratio = ovr / 90f;
            int raw = Mathf.RoundToInt(profile[i] * ratio);
            raw += rng.Next(-2, 3);

            int floor = Mathf.Max(25, ovr - 22);
            raw = Mathf.Clamp(raw, floor, 99);
            result[i] = raw;
            sum += raw;
        }

        // Escalado proporcional: preserva perfil posicional, promedio = ovr
        int targetSum = ovr * 11;
        float factor = (float)targetSum / sum;
        int newSum = 0;
        for (int i = 0; i < 11; i++)
        {
            int scaled = Mathf.RoundToInt(result[i] * factor);
            int floor = Mathf.Max(25, ovr - 22);
            result[i] = Mathf.Clamp(scaled, floor, 99);
            newSum += result[i];
        }

        // Ajustar resto por redondeo/clamp
        int remaining = targetSum - newSum;
        if (remaining > 0)
        {
            var candidates = result.Select((v, i) => new { v, i })
                .Where(x => x.v < 99).OrderByDescending(x => x.v).ToList();
            foreach (var c in candidates)
            {
                if (remaining <= 0) break;
                int add = Mathf.Min(remaining, 99 - c.v);
                result[c.i] += add;
                remaining -= add;
            }
        }
        else if (remaining < 0)
        {
            var candidates = result.Select((v, i) => new { v, i })
                .Where(x => x.v > Mathf.Max(25, ovr - 22)).OrderBy(x => x.v).ToList();
            foreach (var c in candidates)
            {
                if (remaining >= 0) break;
                int sub = Mathf.Min(-remaining, c.v - Mathf.Max(25, ovr - 22));
                result[c.i] -= sub;
                remaining += sub;
            }
        }

        return result;
    }

    static int StableHash(string input)
    {
        unchecked
        {
            uint hash = 2166136261;
            foreach (char c in input)
            {
                hash ^= c;
                hash *= 16777619;
            }
            return (int)hash;
        }
    }

